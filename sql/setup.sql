-- ─── 1. Historia umów z wykonawcami ───────────────────────────────
create table if not exists public.umowy_wykonawcy (
  id         bigint generated by default as identity primary key,
  utworzono  timestamptz not null default now(),
  autor      text,
  etykieta   text,
  dane       jsonb
);

alter table public.umowy_wykonawcy enable row level security;

drop policy if exists "umowy_wyk_select" on public.umowy_wykonawcy;
create policy "umowy_wyk_select" on public.umowy_wykonawcy
  for select to authenticated using (true);

drop policy if exists "umowy_wyk_insert" on public.umowy_wykonawcy;
create policy "umowy_wyk_insert" on public.umowy_wykonawcy
  for insert to authenticated with check (true);

drop policy if exists "umowy_wyk_delete" on public.umowy_wykonawcy;
create policy "umowy_wyk_delete" on public.umowy_wykonawcy
  for delete to authenticated using (true);

create index if not exists umowy_wyk_utworzono_idx
  on public.umowy_wykonawcy (utworzono desc);


-- ─── 2. Ustawienia wspólne dla zespołu ────────────────────────────
--  Trzyma 'konfiguracja_wykonawcy' — wybrane tablice Monday, mapowanie
--  kolumn i adresy skryptów Google. Tylko ten klucz da się zapisać
--  z przeglądarki. Token Monday NIE trafia do bazy — jest sekretem
--  MONDAY_TOKEN funkcji "monday" (supabase/functions/monday/index.ts).
create table if not exists public.ustawienia (
  klucz          text primary key,
  wartosc        jsonb,
  zaktualizowano timestamptz not null default now()
);

alter table public.ustawienia enable row level security;

drop policy if exists "ustawienia_select" on public.ustawienia;
create policy "ustawienia_select" on public.ustawienia
  for select to authenticated using (true);

drop policy if exists "ustawienia_insert" on public.ustawienia;
create policy "ustawienia_insert" on public.ustawienia
  for insert to authenticated with check (klucz = 'konfiguracja_wykonawcy');

drop policy if exists "ustawienia_update" on public.ustawienia;
create policy "ustawienia_update" on public.ustawienia
  for update to authenticated
  using (klucz = 'konfiguracja_wykonawcy') with check (klucz = 'konfiguracja_wykonawcy');


-- ─── 3. Sprawdzenie ───────────────────────────────────────────────
-- Po uruchomieniu powinny pojawić się dwa wiersze:
select table_name, 'OK' as status
from information_schema.tables
where table_schema = 'public'
  and table_name in ('umowy_wykonawcy', 'ustawienia');
